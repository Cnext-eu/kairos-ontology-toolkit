"""Hub-wide bounded-context diagrams under the `ddd` target (DD-230, #846).

Every diagram target selected by file, so nothing could draw a bounded context -- the one
construct that cuts across domain files. These tests pin the hub-wide artifacts, the four
findings from the hub prototype (namespace/class collision, notes out of the diagram,
annotation-gated membership, the canonical ERD's multiplicity helpers), the Silver status
read from authored contracts and bindings, and the projector-level wiring: files land under
`architecture/ddd/contexts/`, the retired per-domain context map is removed, and a renamed
context does not leave its old diagram behind.
"""

from __future__ import annotations

