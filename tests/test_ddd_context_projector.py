class TestSilverStatus:
    @pytest.fixture
    def with_silver(self, tmp_path) -> dict[str, str]:
        contracts = tmp_path / "contracts"
        contracts.mkdir()
        (contracts / "invoice.contract.yaml").write_text(CONTRACT, encoding="utf-8")
        bindings = tmp_path / "bindings"
        bindings.mkdir()
        (bindings / "billing-invoice-lines.binding.yaml").write_text(BINDING, encoding="utf-8")
        return generate_context_artifacts(
            [_domain("client"), _domain("invoice")],
            strategic_path=STRATEGIC,
            contracts_dir=contracts,
            bindings_dir=bindings,
            hub_name="acme-hub",
        )

    def test_status_comes_from_contract_then_binding_then_nothing(self, with_silver):
        notes = with_silver[_key(DESIGN_NOTES_NAME)]
        assert "| Invoice | invoice | AggregateRoot | — | in Silver contract |" in notes
        assert (
            "| Invoice Line | invoice | AggregateMember | Invoice | bound (no contract) |" in notes
        )
        assert "| Invoice Line Tax | invoice | AggregateMember | Invoice | not in Silver |" in notes

    def test_status_is_a_second_stereotype_on_every_member(self, with_silver):
        """Plain-text annotations render everywhere; classDef styling in a classDiagram
        fails the mermaid-cli 11.12 parse, so status is never styling."""
        mmd = with_silver[_key(ALL_CONTEXTS_NAME)]

        def block(name: str) -> str:
            return mmd.split(f"    class {name} {{", 1)[1].split("\n    }", 1)[0]

        assert "<<silver: contract>>" in block("Invoice")
        assert "<<silver: bound>>" in block("InvoiceLine")
        assert "<<architecture only>>" in block("InvoiceLineTax")
        assert "classDef" not in mmd and "cssClass" not in mmd

    def test_default_is_not_in_silver(self, artifacts):
        notes = artifacts[_key(DESIGN_NOTES_NAME)]
        # The legend names every status; only the table rows say what applies.
        assert "| in Silver contract |" not in notes and "| bound (no contract) |" not in notes
        assert "| Invoice | invoice | AggregateRoot | — | not in Silver |" in notes

    def test_a_recorded_disposition_says_why_a_class_is_not_in_silver(self, tmp_path):
        """DD-231 ledger present: the Silver column carries the reason, not just the fact."""
        ledger = tmp_path / "integration" / "discovery" / "class-dispositions.yaml"
        ledger.parent.mkdir(parents=True)
        ledger.write_text(
            textwrap.dedent(
                f"""
                schema_version: 1
                classes:
                  - class: {INVOICE_NS}InvoiceLineTax
                    disposition: architecture-only
                    rationale: tax detail stays in the Taxation context until a source exists
                    decided_by: user
                """
            ),
            encoding="utf-8",
        )
        out = generate_context_artifacts(
            [_domain("invoice")], strategic_path=STRATEGIC, hub_root=tmp_path
        )
        notes = out[_key(DESIGN_NOTES_NAME)]
        assert (
            "| Invoice Line Tax | invoice | AggregateMember | Invoice | not in Silver (architecture-only) |"
            in notes
        )
        assert "| Invoice | invoice | AggregateRoot | — | not in Silver |" in notes

    def test_a_qname_without_a_load_result_is_reported_not_guessed(self, tmp_path):
        contracts = tmp_path / "contracts"
        contracts.mkdir()
        (contracts / "invoice.contract.yaml").write_text(
            CONTRACT.replace(f"class: {INVOICE_NS}Invoice", "class: acme-inv:Invoice"),
            encoding="utf-8",
        )
        out = generate_context_artifacts(
            [_domain("invoice")], strategic_path=STRATEGIC, contracts_dir=contracts
        )
        notes = out[_key(DESIGN_NOTES_NAME)]
        assert "## Unresolved class references" in notes
        assert "invoice.contract.yaml: acme-inv:Invoice" in notes


