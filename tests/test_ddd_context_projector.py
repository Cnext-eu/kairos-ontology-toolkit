def _project_ddd(hub: Path, output: Path) -> None:
    run_projections(
        ontologies_path=hub / "model" / "ontologies",
        catalog_path=None,
        output_path=output,
        target="ddd",
    )


class TestProjectorWiring:
    def test_context_artifacts_land_under_the_ddd_target(self, hub, tmp_path):
        output = tmp_path / "publish"
        _project_ddd(hub, output)
        ddd = output / "architecture" / "ddd"
        assert (ddd / "client-aggregate-overview.mmd").is_file()
        assert (ddd / CONTEXTS_SUBDIR / CONTEXT_MAP_NAME).is_file()
        assert (ddd / CONTEXTS_SUBDIR / ALL_CONTEXTS_NAME).is_file()
        assert (ddd / CONTEXTS_SUBDIR / "BillingContext.mmd").is_file()
        assert (ddd / _PROJECTION_MANIFEST_NAME).is_file()
        assert not (ddd / "client-context-map.mmd").exists()

    def test_the_retired_per_domain_context_map_is_removed_once(self, hub, tmp_path):
        """An earlier toolkit wrote it and no manifest owns it, so it is named explicitly."""
        output = tmp_path / "publish"
        ddd = output / "architecture" / "ddd"
        ddd.mkdir(parents=True)
        (ddd / "client-context-map.mmd").write_text("graph LR\n", encoding="utf-8")
        _project_ddd(hub, output)
        assert not (ddd / "client-context-map.mmd").exists()

    def test_a_renamed_context_does_not_leave_its_diagram_behind(self, hub, tmp_path):
        output = tmp_path / "publish"
        _project_ddd(hub, output)
        contexts = output / "architecture" / "ddd" / CONTEXTS_SUBDIR
        assert (contexts / "TaxContext.mmd").is_file()

        strategic = hub / "model" / "extensions" / "ddd-contexts-ext.ttl"
        overlay = hub / "model" / "extensions" / "invoice-ddd-ext.ttl"
        for path in (strategic, overlay):
            path.write_text(
                path.read_text(encoding="utf-8").replace("TaxContext", "TaxationContext"),
                encoding="utf-8",
            )
        _project_ddd(hub, output)
        assert (contexts / "TaxationContext.mmd").is_file()
        assert not (contexts / "TaxContext.mmd").exists()

    def test_a_hub_without_ddd_input_gets_no_contexts(self, hub, tmp_path):
        """No overlay, no strategic file: no `contexts/`. The manifest still exists, because
        DD-232's language artifacts are written for every hub with a class."""
        for path in (hub / "model" / "extensions").glob("*ddd*"):
            path.unlink()
        output = tmp_path / "publish"
        _project_ddd(hub, output)
        ddd = output / "architecture" / "ddd"
        assert not (ddd / CONTEXTS_SUBDIR).exists()
        assert (ddd / _PROJECTION_MANIFEST_NAME).is_file()
        assert (ddd / "ubiquitous-language.ttl").is_file()
