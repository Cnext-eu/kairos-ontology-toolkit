from rdflib import Graph

from kairos_ontology.core.projections.ddd_context_projector import (
    ALL_CONTEXTS_NAME,
    CONTEXT_MAP_NAME,
    CONTEXTS_SUBDIR,
    DESIGN_NOTES_NAME,
    ContextDomain,
    generate_context_artifacts,
)
from kairos_ontology.core.projector import _PROJECTION_MANIFEST_NAME, run_projections

ACME_HUB = Path(__file__).parent / "scenarios" / "acme-hub"
ONTOLOGIES = ACME_HUB / "model" / "ontologies"
EXTENSIONS = ACME_HUB / "model" / "extensions"
STRATEGIC = EXTENSIONS / "ddd-contexts-ext.ttl"

INVOICE_NS = "https://acme.example/ontology/invoice#"
CLIENT_NS = "https://acme.example/ontology/client#"


def _domain(name: str) -> ContextDomain:
    graph = Graph()
    graph.parse(ONTOLOGIES / f"{name}.ttl", format="turtle")
    return ContextDomain(
        name=name,
        graph=graph,
        file=ONTOLOGIES / f"{name}.ttl",
        local_graph=graph,
        overlay_path=EXTENSIONS / f"{name}-ddd-ext.ttl",
    )


@pytest.fixture(scope="module")
def artifacts() -> dict[str, str]:
    return generate_context_artifacts(
        [_domain("client"), _domain("invoice")], strategic_path=STRATEGIC, hub_name="acme-hub"
    )


def _key(name: str) -> str:
    return f"{CONTEXTS_SUBDIR}/{name}"


class TestArtifactSet:
    def test_one_map_one_overview_one_notes_and_one_file_per_non_empty_context(self, artifacts):
        assert set(artifacts) == {
            _key(CONTEXT_MAP_NAME),
            _key(ALL_CONTEXTS_NAME),
            _key(DESIGN_NOTES_NAME),
            _key("BillingContext.mmd"),
            _key("TaxContext.mmd"),
            _key("ClientContext.mmd"),
            _key("ReferenceContext.mmd"),
        }

    def test_every_diagram_opens_with_the_shared_header(self, artifacts):
        for name, text in artifacts.items():
            if name.endswith(".mmd"):
                assert text.startswith("---\nconfig:\n  layout: elk\n---\n%% Generated by"), name

    def test_deterministic(self):
        first = generate_context_artifacts(
            [_domain("client"), _domain("invoice")], strategic_path=STRATEGIC
        )
        second = generate_context_artifacts(
            [_domain("invoice"), _domain("client")], strategic_path=STRATEGIC
        )
        assert first == second

    def test_no_ddd_input_yields_nothing(self):
        graph = Graph()
        graph.parse(ONTOLOGIES / "client.ttl", format="turtle")
        bare = ContextDomain(name="client", graph=graph, local_graph=graph)
        assert generate_context_artifacts([bare]) == {}


