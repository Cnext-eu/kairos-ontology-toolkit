class TestClassDiagrams:
    def test_namespace_per_context_with_pattern_annotations(self, artifacts):
        mmd = artifacts[_key(ALL_CONTEXTS_NAME)]
        assert "namespace BillingContext {" in mmd
        assert "<<AggregateRoot>>" in mmd and "<<ValueObject>>" in mmd
        assert "    class Invoice {" in mmd
        assert "string invoiceNumber" in mmd

    def test_member_without_a_context_inherits_its_roots(self, artifacts):
        """InvoiceLine carries only `aggregateRoot acme-inv:Invoice`; it belongs to Billing."""
        billing = artifacts[_key("BillingContext.mmd")]
        namespace = billing.split("namespace BillingContext {", 1)[1].split("\n}", 1)[0]
        assert "class InvoiceLine {" in namespace
        assert "Invoice *-- InvoiceLine : aggregate" in billing

    def test_cross_context_aggregate_is_drawn_not_hidden(self, artifacts):
        """InvoiceLineTax sits in Taxation but is rooted on Invoice in Billing."""
        mmd = artifacts[_key(ALL_CONTEXTS_NAME)]
        tax = mmd.split("namespace TaxContext {", 1)[1].split("\n}", 1)[0]
        assert "class InvoiceLineTax {" in tax
        assert "Invoice *-- InvoiceLineTax : aggregate" in mmd

    def test_neighbours_are_stubs_with_a_reason(self, artifacts):
        """In the Taxation diagram, Invoice is outside the context: a stub saying where it lives."""
        tax = artifacts[_key("TaxContext.mmd")]
        assert "namespace TaxContext {" in tax
        assert "namespace BillingContext" not in tax
        assert "<<context: Billing>>" in tax

    def test_unassigned_hub_class_reached_by_a_member_is_a_stub(self, artifacts):
        """InvoiceTag has a tactical pattern but no context; it is drawn only where reached."""
        mmd = artifacts[_key(ALL_CONTEXTS_NAME)]
        assert "namespace" in mmd
        assert mmd.count("class InvoiceTag {") <= 1

    def test_membership_is_annotation_gated(self, artifacts):
        """No import-closure class appears inside a namespace."""
        mmd = artifacts[_key(ALL_CONTEXTS_NAME)]
        for block in mmd.split("namespace ")[1:]:
            body = block.split("\n}", 1)[0]
            assert "<<bsp/" not in body and "refp" not in body

    def test_namespace_id_never_equals_a_member_class_id(self, tmp_path):
        """Mermaid rejects a class as its own parent; the context id is suffixed instead."""
        ttl = textwrap.dedent(
            """
            @prefix owl: <http://www.w3.org/2002/07/owl#> .
            @prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
            @prefix ex: <https://example.test/ontology/party#> .
            <https://example.test/ontology/party> a owl:Ontology .
            ex:Party a owl:Class ; rdfs:label "Party" .
            """
        )
        overlay = textwrap.dedent(
            """
            @prefix kairos-ddd: <https://kairos.cnext.eu/ddd#> .
            @prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
            @prefix ex: <https://example.test/ontology/party#> .
            @prefix ctx: <https://example.test/ddd#> .
            ctx:Party a kairos-ddd:BoundedContext ; rdfs:label "Party" .
            ex:Party kairos-ddd:boundedContext ctx:Party .
            """
        )
        onto = tmp_path / "party.ttl"
        onto.write_text(ttl, encoding="utf-8")
        ov = tmp_path / "party-ddd-ext.ttl"
        ov.write_text(overlay, encoding="utf-8")
        graph = Graph()
        graph.parse(onto, format="turtle")
        out = generate_context_artifacts(
            [
                ContextDomain(
                    name="party", graph=graph, file=onto, local_graph=graph, overlay_path=ov
                )
            ]
        )
        mmd = out[_key(ALL_CONTEXTS_NAME)]
        assert "namespace Party_context {" in mmd
        assert "    class Party {" in mmd


