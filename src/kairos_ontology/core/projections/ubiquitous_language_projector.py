def _pref_label(graph: Graph, cls: URIRef) -> Literal:
    value = graph.value(cls, RDFS.label)
    if isinstance(value, Literal):
        return Literal(str(value), lang=value.language or "en")
    return Literal(extract_local_name(str(cls)), lang="en")


def language_header(hub_name: str) -> str:
    """Deterministic Turtle header: which toolkit wrote it, never when (drift-gated lane)."""
    return "\n".join(
        [
            f"# Generated by kairos-ontology {_toolkit_version()} -- do not edit",
            f"# Ubiquitous language of {hub_name} (DD-232): one skos:Concept per hub class,",
            "# derived from the ontology, the DDD overlay, the discovery glossary and the",
            "# bindings. Regenerate with `kairos-ontology project --target ddd`.",
            "",
        ]
    )


def render_ubiquitous_language(model: LanguageModel) -> str:
    graph = Graph()
    terms = Namespace(model.terms_ns)
    graph.bind("skos", SKOS)
    graph.bind("rdfs", RDFS)
    graph.bind("dct", DCTERMS)
    graph.bind("terms", terms)

    scheme = URIRef(model.terms_ns.rstrip("#/"))
    graph.add((scheme, RDF.type, SKOS.ConceptScheme))
    graph.add((scheme, RDFS.label, Literal(f"{model.hub_name} ubiquitous language", lang="en")))
    graph.add(
        (
            scheme,
            DCTERMS.description,
            Literal(
                "Generated from the canonical ontology, its DDD overlay, the discovery glossary "
                "and the EntityBindings (DD-232). Derived, therefore current: never edit by hand."
            ),
        )
    )

    concepts: dict[URIRef, URIRef] = {}
    for cls in model.classes():
        concept = terms[model.term_ids[cls]]
        concepts[cls] = concept
        graph.add((concept, RDF.type, SKOS.Concept))
        graph.add((concept, SKOS.inScheme, scheme))
        graph.add((concept, SKOS.prefLabel, _pref_label(model.graph, cls)))
        comment = model.graph.value(cls, RDFS.comment)
        if comment is not None:
            graph.add((concept, SKOS.definition, Literal(str(comment))))
        for definition in model.glossary_definitions.get(cls, []):
            graph.add(
                (concept, SKOS.note, Literal(f"Business definition (discovery): {definition}"))
            )
        graph.add((concept, SKOS.exactMatch, cls))
        for parent in model.industry.get(cls, []):
            graph.add((concept, SKOS.broadMatch, parent))
        alt = set(model.base.alt_labels.get(cls, [])) | set(model.glossary_alt.get(cls, []))
        for label in sorted(alt):
            graph.add((concept, SKOS.altLabel, Literal(label, lang="en")))
        for note in model.base.scope_notes.get(cls, []):
            graph.add((concept, SKOS.scopeNote, Literal(note)))
        for example in model.base.examples.get(cls, []):
            graph.add((concept, SKOS.example, Literal(example)))
        for relation in model.sources.get(cls, []):
            graph.add((concept, SKOS.hiddenLabel, Literal(relation)))
        status = model.base.silver.get(cls, STATUS_UNBOUND)
        disposition = model.base.dispositions.get(cls)
        note = f"silver: {status}" + (f"; disposition: {disposition}" if disposition else "")
        graph.add((concept, SKOS.editorialNote, Literal(note)))

    for group_id, label, classes in model.groups():
        if not classes:
            continue
        collection = terms[group_id]
        graph.add((collection, RDF.type, SKOS.Collection))
        graph.add((collection, SKOS.inScheme, scheme))
        graph.add((collection, SKOS.prefLabel, Literal(label, lang="en")))
        for cls in classes:
            graph.add((collection, SKOS.member, concepts[cls]))

    body = graph.serialize(format="turtle")
    return language_header(model.hub_name) + body


def generate_ubiquitous_language(model: LanguageModel) -> dict[str, str]:
    """``{"ubiquitous-language.ttl": content}``; empty only when the hub declares no class."""
    if not model.base.hub_classes:
        return {}
    return {UBIQUITOUS_LANGUAGE_NAME: render_ubiquitous_language(model)}


def language_inputs(hub_root: Optional[Path]) -> dict[str, Any]:
    """The ``kairos.yaml`` switches for the language artifacts (samples default off)."""
    if hub_root is None:
        return {"samples": 0}
    from ..hub_config import load_hub_config

    section = load_hub_config(hub_root).get("projections")
    guide = section.get("concept_guide") if isinstance(section, dict) else None
    if not isinstance(guide, dict) or not guide.get("samples"):
        return {"samples": 0}
    raw = guide.get("max_samples", 3)
    try:
        return {"samples": max(0, int(raw))}
    except (TypeError, ValueError):
        return {"samples": 3}
