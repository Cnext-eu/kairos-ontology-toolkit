"""Shipped reference-list members as a dbt seed (DD-257, #1126 P2).

A kind-1 reference list ships its members as individuals in the reference models. A hub
binds it like any other entity, through a seed read by a contracted model. This module
turns the members a resolved closure holds into that seed: one row per member, keyed on
``(code_list, code)``, with the upstream IRI as an ordinary column. The seed's column
docs are generated too, so the snapshot version and source travel with the rows and dbt
loads every column as text (a code such as ``02`` must not become the integer 2).

Nothing here reads serialized RDF: callers pass the graph of a closure loaded through
:func:`kairos_ontology.core.ontology_loader.load_ontology` (DD-243).
"""

from __future__ import annotations

import csv
import io
from dataclasses import dataclass

import yaml
from rdflib import OWL, RDF, RDFS, SKOS, Graph, Literal, URIRef
from rdflib.namespace import DCTERMS

from .projections.uri_utils import camel_to_snake

#: First line of every generated seed-docs document. ``export-reference-list`` only
#: overwrites a seed whose docs start with it, so a hand-authored seed is never replaced.
GENERATED_MARKER = "# Generated by `kairos-ontology export-reference-list` (DD-257)."

#: Seed columns, in order.
COLUMNS = ("code_list", "code", "name", "iri")

#: Text lengths a column's type is rounded up to, so the declared type changes only when a
#: release crosses a bucket, not on every new member.
_LENGTH_BUCKETS = (16, 32, 64, 128, 256, 512, 1024, 4000, 8000)


class ReferenceListError(ValueError):
    """The class has no exportable members, or its members do not form a valid seed."""


@dataclass(frozen=True)
class ReferenceMember:
    code_list: str
    code: str
    name: str
    iri: str


@dataclass(frozen=True)
class ListProvenance:
    """One list class the members came from, with its snapshot metadata."""

    uri: str
    name: str
    version: str | None
    source: str | None


@dataclass(frozen=True)
class ReferenceList:
    class_uri: str
    members: tuple[ReferenceMember, ...]
    lists: tuple[ListProvenance, ...]
    #: Members skipped because they carry no code (``rdf:value`` or ``skos:notation``).
    skipped: tuple[str, ...]


def local_name(uri: str) -> str:
    return uri.rstrip("/#").rsplit("#", 1)[-1].rsplit("/", 1)[-1]


def default_seed_name(class_uri: str) -> str:
    """``unece:TransportModeCodeList`` → ``transport_mode_code_list``."""
    return camel_to_snake(local_name(class_uri)).replace("-", "_")


def _text(graph: Graph, subject: URIRef, *predicates: URIRef) -> str | None:
    """The first predicate's value, preferring English, then untagged, then any language.

    Ties are broken by the literal's text so the choice never depends on parse order.
    """
    for predicate in predicates:
        values = [
            value for value in graph.objects(subject, predicate) if isinstance(value, Literal)
        ]
        if not values:
            continue

        def rank(value: Literal) -> tuple[int, str]:
            lang = (value.language or "").lower()
            order = 0 if lang == "en" or lang.startswith("en-") else 1 if not lang else 2
            return order, str(value)

        text = str(min(values, key=rank)).strip()
        if text:
            return text
    return None


def collect_reference_list(graph: Graph, class_uri: str) -> ReferenceList:
    """Collect the members of *class_uri* and of every class below it in *graph*.

    Passing the hub's governed class (``ref:TransportModeCode``) collects every list the hub
    took in with ``unece:TransportModeCodeList rdfs:subClassOf ref:TransportModeCode``.
    Each member's ``code_list`` is its most specific asserted type among those classes.
    """
    root = URIRef(class_uri)
    if (root, RDF.type, OWL.Class) not in graph and (root, RDF.type, RDFS.Class) not in graph:
        raise ReferenceListError(f"class does not resolve in the closure: {class_uri}")
    classes = {root, *graph.transitive_subjects(RDFS.subClassOf, root)}
    classes = {item for item in classes if isinstance(item, URIRef)}

    members: list[ReferenceMember] = []
    skipped: list[str] = []
    used_lists: set[URIRef] = set()
    seen: dict[tuple[str, str], str] = {}
    duplicates: list[str] = []
    subjects = {
        subject
        for cls in classes
        for subject in graph.subjects(RDF.type, cls)
        if isinstance(subject, URIRef)
    }
    for subject in sorted(subjects, key=str):
        types = {item for item in graph.objects(subject, RDF.type) if item in classes}
        # The most specific type: one with no other candidate type below it.
        specific = sorted(
            (
                item
                for item in types
                if not any(
                    other != item and (other, RDFS.subClassOf, item) in graph for other in types
                )
            ),
            key=str,
        )
        list_uri = specific[0] if specific else min(types, key=str)
        code = _text(graph, subject, RDF.value, SKOS.notation)
        if code is None:
            skipped.append(str(subject))
            continue
        name = _text(graph, subject, RDFS.label, SKOS.prefLabel, RDFS.comment) or ""
        code_list = local_name(str(list_uri))
        key = (code_list, code)
        if key in seen:
            duplicates.append(f"{code_list} {code!r}: {seen[key]} and {subject}")
            continue
        seen[key] = str(subject)
        used_lists.add(list_uri)
        members.append(ReferenceMember(code_list, code, name, str(subject)))

    if duplicates:
        raise ReferenceListError(
            "two members share a (code_list, code) key, so the seed would have no unique "
            "key:\n  " + "\n  ".join(duplicates)
        )
    if not members:
        raise ReferenceListError(
            f"{class_uri} has no members with a code in this closure. A list the reference "
            "models ship (kind 1) has individuals with rdf:value; a hub-loaded standard "
            "(kind 2) or a client-owned list (kind 3) is bound from its source instead "
            "(DD-257)."
        )
    lists = tuple(
        ListProvenance(
            uri=str(item),
            name=local_name(str(item)),
            version=_text(graph, item, OWL.versionInfo),
            source=next(
                (str(value) for value in sorted(graph.objects(item, DCTERMS.source))), None
            ),
        )
        for item in sorted(used_lists, key=str)
    )
    members.sort(key=lambda item: (item.code_list, item.code))
    return ReferenceList(class_uri, tuple(members), lists, tuple(skipped))


def render_seed_csv(reference: ReferenceList) -> str:
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(COLUMNS)
    for item in reference.members:
        writer.writerow((item.code_list, item.code, item.name, item.iri))
    return buffer.getvalue()


def _bucket(length: int) -> int:
    return next((size for size in _LENGTH_BUCKETS if size >= length), _LENGTH_BUCKETS[-1])


def column_lengths(reference: ReferenceList) -> dict[str, int]:
    """The bucketed maximum text length of each column."""
    lengths = dict.fromkeys(COLUMNS, 1)
    for item in reference.members:
        for column, value in zip(COLUMNS, (item.code_list, item.code, item.name, item.iri)):
            lengths[column] = max(lengths[column], len(value))
    return {column: _bucket(length) for column, length in lengths.items()}


def render_seed_docs(
    reference: ReferenceList,
    seed_name: str,
    column_types: dict[str, str] | None,
    origin: dict[str, str] | None = None,
) -> str:
    """The seed's dbt properties document, headed by :data:`GENERATED_MARKER`.

    *column_types* maps each column to the adapter's text type. ``None`` leaves typing to
    dbt, which then infers numbers from codes such as ``1`` or ``02``. *origin* is written
    into the header as ``# key: value`` lines (``class`` and ``domain`` or ``ontology``),
    so ``export-reference-list --all`` can regenerate or check the seed without being told
    what it came from.
    """
    snapshots = "; ".join(
        f"{item.name}: snapshot {item.version or 'unversioned'}, source {item.source or 'unstated'}"
        for item in reference.lists
    )
    seed: dict[str, object] = {
        "name": seed_name,
        "description": (
            f"Members of {reference.class_uri} as shipped by the reference models "
            f"({len(reference.members)} rows). {snapshots}. Local extensions belong in "
            f"{seed_name}_local, never in this file."
        ),
    }
    if column_types:
        seed["config"] = {"column_types": dict(column_types)}
    seed["columns"] = [
        {"name": "code_list", "description": "Local name of the list class the code belongs to."},
        {"name": "code", "description": "The code (rdf:value); unique within its code_list."},
        {"name": "name", "description": "The code's name (rdfs:label)."},
        {
            "name": "iri",
            "description": "The member's upstream IRI. A column, not the key: the IRI scheme "
            "can change upstream.",
        },
    ]
    body = yaml.safe_dump(
        {"version": 2, "seeds": [seed]},
        sort_keys=False,
        allow_unicode=True,
        width=100,
    )
    origin_lines = "".join(f"# {key}: {value}\n" for key, value in (origin or {}).items())
    return (
        f"{GENERATED_MARKER}\n"
        f"{origin_lines}"
        "# Re-run the command after each reference-models upgrade instead of editing this file.\n"
        f"{body}"
    )


def is_generated(docs_text: str) -> bool:
    return docs_text.startswith(GENERATED_MARKER)


#: Header keys :func:`read_origin` returns.
ORIGIN_KEYS = ("class", "domain", "ontology")


def read_origin(docs_text: str) -> dict[str, str]:
    """The ``# key: value`` origin lines of a generated header, before the YAML body."""
    origin: dict[str, str] = {}
    for line in docs_text.splitlines()[1:]:
        if not line.startswith("#"):
            break
        key, sep, value = line[1:].strip().partition(":")
        if sep and key.strip() in ORIGIN_KEYS and value.strip():
            origin[key.strip()] = value.strip()
    return origin


@dataclass(frozen=True)
class SeedDiff:
    added: tuple[tuple[str, str], ...]
    removed: tuple[tuple[str, str], ...]
    changed: tuple[tuple[str, str], ...]


def diff_seed(current_csv: str, expected: ReferenceList) -> SeedDiff:
    """Compare a seed CSV on disk with the members the closure holds, keyed on the code."""
    rows = csv.DictReader(io.StringIO(current_csv))
    current = {
        (row.get("code_list", ""), row.get("code", "")): (row.get("name", ""), row.get("iri", ""))
        for row in rows
    }
    wanted = {(item.code_list, item.code): (item.name, item.iri) for item in expected.members}
    return SeedDiff(
        added=tuple(sorted(wanted.keys() - current.keys())),
        removed=tuple(sorted(current.keys() - wanted.keys())),
        changed=tuple(
            sorted(key for key in wanted.keys() & current.keys() if wanted[key] != current[key])
        ),
    )
